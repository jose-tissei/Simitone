"""Generates Mgfx.csproj (SDK style) from the FSOMonoGame 2MGFX Protobuild definition, so the effect compiler
that matches the game's MGFX v8 format can be built with plain `dotnet build`. Run from Tools/Render/Mgfx."""
import re, os

BS = chr(92)
root = os.path.dirname(os.path.abspath(__file__))
fsomg = os.path.normpath(os.path.join(root, '..', '..', '..', 'FreeSO', 'Other', 'libs', 'FSOMonoGame'))
d = open(os.path.join(fsomg, 'Build', 'Projects', '2MGFX.definition'), encoding='utf8').read()
items = re.findall(r'<Compile Include="([^"]+)"(?:\s*/>|>\s*<Link>([^<]+)</Link>)', d)
lines = []
for inc, link in items:
    inc = inc.replace(BS, '/')
    if inc.startswith('..'):
        rel = inc[len('../../'):]
        lines.append('    <Compile Include="$(Fsomg)/%s" Link="Fx/%s" />' % (rel, link.replace(BS, '/')))
    else:
        lines.append('    <Compile Include="$(Fsomg)/Tools/2MGFX/%s" Link="Fx/%s" />' % (inc, inc))

proj = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- Effect compiler of the FSOMonoGame fork the game ships with (writes MGFX version 8). Generated by gen_csproj.py. -->
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net9.0-windows</TargetFramework>
    <PlatformTarget>x64</PlatformTarget>
    <RootNamespace>TwoMGFX</RootNamespace>
    <AssemblyName>2mgfx</AssemblyName>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <DefineConstants>TRACE;WINDOWS</DefineConstants>
    <NoWarn>1591;0436;CS0168;CS0219;CS0649;CS0169;CS8981;SYSLIB0003</NoWarn>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <ImplicitUsings>disable</ImplicitUsings>
    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
    <Nullable>disable</Nullable>
    <Fsomg>$(MSBuildThisFileDirectory)../../../FreeSO/Other/libs/FSOMonoGame</Fsomg>
    <Deps>$(Fsomg)/ThirdParty/Dependencies</Deps>
  </PropertyGroup>
  <ItemGroup>
%s
  </ItemGroup>
  <ItemGroup>
    <Reference Include="CppNet"><HintPath>$(Deps)/CppNet/CppNet.dll</HintPath></Reference>
    <Reference Include="SharpDX.D3DCompiler"><HintPath>$(Deps)/SharpDX/SharpDX.D3DCompiler.dll</HintPath></Reference>
    <Reference Include="SharpDX"><HintPath>$(Deps)/SharpDX/net40/SharpDX.dll</HintPath></Reference>
  </ItemGroup>
</Project>
""" % '\n'.join(lines)
open(os.path.join(root, 'Mgfx.csproj'), 'w', encoding='utf8').write(proj)
print(len(items), 'compile items')
